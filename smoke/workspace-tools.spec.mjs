import { expect,test } from '@playwright/test'

test('agency can find all AI providers and generate a printable proposal',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Agency'}).click()
  await page.getByRole('link',{name:'Workspace settings',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Integrations',exact:true})).toBeVisible()
  const viewport=page.viewportSize()
  expect((await page.locator('.sidebar').boundingBox()).height).toBeLessThanOrEqual(viewport.height)
  for(const provider of ['Devin','Cursor','Claude','Codex','ChatGPT','Grok','Vercel','Supabase','Cloudflare','Firebase','Netlify','WHM','cPanel','Stripe','Sentry','GitHub Actions']) await expect(page.locator('#configure-provider strong').getByText(provider,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Add integration',exact:true}).click()
  await expect(page.getByLabel('API key',{exact:true})).toHaveAttribute('type','password')
  await page.getByRole('combobox',{name:'Provider',exact:true}).selectOption('Codex')
  await expect(page.getByLabel('OpenAI Codex model ID')).toBeVisible()
  await page.getByRole('button',{name:'Close setup',exact:true}).click()
  await page.getByRole('button',{name:'Add Cloudflare',exact:true}).click()
  await expect(page.getByLabel('Cloudflare zone ID')).toBeVisible()
  await page.getByRole('navigation',{name:'Settings sections'}).getByRole('link',{name:'Deployments'}).click()
  await page.getByText('Build a multi-target release workflow',{exact:true}).click()
  await page.getByRole('checkbox',{name:'Cloudflare Workers',exact:true}).check()
  await page.getByRole('checkbox',{name:'Firebase Hosting',exact:true}).check()
  await expect(page.getByLabel('GitHub Actions workflow')).toHaveValue(/Deploy Vercel[\s\S]*Deploy Cloudflare Worker[\s\S]*Deploy Firebase Hosting/)
  await page.getByRole('navigation',{name:'Settings sections'}).getByRole('link',{name:'Operations'}).click()
  await page.getByText('Record a settled Paynow collection',{exact:true}).click()
  await page.getByLabel('Paynow reference',{exact:true}).fill('smoke-'+Date.now())
  await page.getByLabel('Gross collected',{exact:true}).fill('12.50')
  await page.getByLabel('App or business tag',{exact:true}).last().fill('Smoke app')
  await page.getByRole('button',{name:'Save Paynow collection'}).click()
  await page.getByRole('button',{name:'View collections'}).click()
  await expect(page.getByText(/USD.*captured.*after refunds/)).toBeVisible()
  await page.getByText('Breakdown by app or business',{exact:true}).click()
  await page.getByRole('button',{name:'Filter by Smoke app',exact:true}).click()
  await expect(page.getByLabel('App or business tag',{exact:true}).first()).toHaveValue('Smoke app')
  await page.getByRole('button',{name:'Show all apps and businesses',exact:true}).click()
  await expect(page.getByLabel('App or business tag',{exact:true}).first()).toHaveValue('')
  await page.getByRole('link',{name:'Accounts & ERP',exact:true}).click()
  await page.getByText('New ERP document',{exact:true}).click()
  await page.getByRole('textbox',{name:'Title',exact:true}).fill('Maintenance proposal '+Date.now())
  await page.getByRole('textbox',{name:'Document body'}).fill('Review the staging workflow.')
  await page.getByRole('button',{name:'Generate and save document'}).click()
  await expect(page.getByText('Review the staging workflow.',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Print or save as PDF'})).toBeVisible()
  await expect(page.getByRole('link',{name:'Platform admin',exact:true})).toHaveCount(0)
})
